// Round 11: the ids of the vanilla blocks and items, fixed in one place so the content
// modules (built side by side) can refer to each other's things: a recipe in
// building.js uses iron_ingot from items-vanilla.js, a mob drop uses leather, a crop
// uses its seeds. An id never changes meaning once released. A block with
// variants (facing, open, half, growth stage) owns `n` consecutive ids starting at
// its constant (the order is described next to it); its owner module defines
// all of them. Owners: building.js (1024-1535), nature.js (blocks 1536-1791,
// items 400-479), containers.js (1792-1855), redstone.js (1856-2047),
// items-vanilla.js (items 320-399, 480-639). A module may add more ids in its
// own ranges (after these). Existing blocks keep their core ids (base.js BLOCK):
// oak planks 8, oak log 6, birch log 25, spruce (pine) log 27, ... ; items keep
// theirs (ITEM: stick 256, coal 257, gold ingot 259, apple 261, ...).
// White wool is the core WOOL (24); the plain terracotta is TERRACOTTA (31).
// A leaf module (imports nothing).

